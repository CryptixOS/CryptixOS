"""
Writes the ZLib test vectors as a C++ header: each case is a zlib stream
made with Python's zlib, plus the recipe that main.cpp uses to rebuild the
uncompressed data (so megabytes of plaintext don't end up in the header).
The recipes must match Generate() in main.cpp.
"""

import sys
import zlib


def text(size: int) -> bytes:
    # Compressible: dynamic Huffman blocks with lots of back-references
    out = bytearray()
    line = 0
    while len(out) < size:
        out += f'drwxr-xr-x root root {line * 37 % 9973} usr/lib/file-{line % 113}.so\n'.encode()
        line += 1
    return bytes(out[:size])


def noise(size: int, seed: int) -> bytes:
    # Incompressible (zlib emits stored blocks): a 32-bit LCG
    out = bytearray(size)
    state = seed
    for i in range(size):
        state = (state * 1103515245 + 12345) & 0xffffffff
        out[i] = state >> 24
    return bytes(out)


def build(recipe):
    data = b''
    for kind, size, seed in recipe:
        data += text(size) if kind == 'text' else noise(size, seed)
    return data


# name, zlib level, [(kind, size, seed)], initial output buffer size
CASES = [
    ('Empty', 6, [], 0),
    ('ShortFixedHuffman', 9, [('text', 40, 0)], 0),
    ('StoredLevel0', 0, [('text', 100000, 0)], 0),
    ('IncompressibleNoise', 6, [('noise', 70000, 7)], 0),
    ('LargeDynamicHuffman', 9, [('text', 3 * 1024 * 1024, 0)], 0),
    # A 16 byte first buffer forces many grows mid-block
    ('GrowFromTinyBuffer', 6, [('text', 512 * 1024, 0)], 16),
    ('MixedBlockTypes', 6, [('text', 200000, 0), ('noise', 50000, 3),
                            ('text', 200000, 0)], 0),
]


def array(data: bytes) -> str:
    return ', '.join(str(b) for b in data) or '0'


def main():
    out = [
        '// Generated by gen-vectors.py, do not edit',
        '#pragma once',
        '#include <cstddef>',
        '#include <cstdint>',
        '',
        'struct Chunk { int Kind; std::size_t Size; std::uint32_t Seed; };',
        'struct Case',
        '{',
        '    const char*          Name;',
        '    const std::uint8_t*  Compressed;',
        '    std::size_t          CompressedSize;',
        '    const Chunk*         Chunks;',
        '    std::size_t          ChunkCount;',
        '    std::size_t          InitialSize;',
        '};',
        '',
    ]
    entries = []
    for name, level, recipe, initial in CASES:
        compressed = zlib.compress(build(recipe), level)
        out.append(f'inline constexpr std::uint8_t {name}Data[] = {{{array(compressed)}}};')
        chunks = ', '.join(f'{{{0 if k == "text" else 1}, {s}, {seed}}}'
                           for k, s, seed in recipe) or '{0, 0, 0}'
        out.append(f'inline constexpr Chunk {name}Chunks[] = {{{chunks}}};')
        entries.append(f'    {{"{name}", {name}Data, {len(compressed)}, '
                       f'{name}Chunks, {len(recipe)}, {initial}}},')
    out += ['', 'inline constexpr Case Cases[] = {', *entries, '};', '']

    with open(sys.argv[1], 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
